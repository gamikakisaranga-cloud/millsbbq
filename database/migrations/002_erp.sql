-- Mills ERP expansion. Safe to run after database/schema.sql.
ALTER TABLE users MODIFY role ENUM('CUSTOMER','ADMIN','OWNER','STORE_ADMIN','ORDER_MANAGER','INVENTORY_MANAGER','CUSTOMER_SUPPORT') NOT NULL DEFAULT 'CUSTOMER';
ALTER TABLE products
  ADD COLUMN sku VARCHAR(80) NULL,
  ADD COLUMN compare_price_cents INT NULL,
  ADD COLUMN cost_price_cents INT NULL,
  ADD COLUMN category_id CHAR(36) NULL,
  ADD COLUMN image_url VARCHAR(1000) NULL,
  ADD COLUMN low_stock_threshold INT NOT NULL DEFAULT 5,
  ADD COLUMN track_inventory TINYINT(1) NOT NULL DEFAULT 1,
  ADD COLUMN allow_oversell TINYINT(1) NOT NULL DEFAULT 0,
  ADD COLUMN published_at DATETIME NULL;
ALTER TABLE orders
  ADD COLUMN payment_status ENUM('PENDING','PAID','FAILED','PARTIALLY_REFUNDED','REFUNDED') NOT NULL DEFAULT 'PENDING',
  ADD COLUMN fulfilment_status ENUM('UNFULFILLED','PROCESSING','PACKED','SHIPPED','DELIVERED','CANCELLED') NOT NULL DEFAULT 'UNFULFILLED',
  ADD COLUMN discount_cents INT NOT NULL DEFAULT 0,
  ADD COLUMN tax_cents INT NOT NULL DEFAULT 0,
  ADD COLUMN carrier VARCHAR(100) NULL,
  ADD COLUMN tracking_number VARCHAR(190) NULL,
  ADD COLUMN customer_note TEXT NULL,
  ADD COLUMN internal_note TEXT NULL;
UPDATE orders SET payment_status = CASE WHEN status IN ('PAID','PROCESSING','SHIPPED','DELIVERED') THEN 'PAID' WHEN status='CANCELLED' THEN 'FAILED' WHEN status='REFUNDED' THEN 'REFUNDED' ELSE 'PENDING' END,
 fulfilment_status = CASE WHEN status IN ('PAID','PROCESSING') THEN 'PROCESSING' WHEN status='SHIPPED' THEN 'SHIPPED' WHEN status='DELIVERED' THEN 'DELIVERED' WHEN status IN ('CANCELLED','REFUNDED') THEN 'CANCELLED' ELSE 'UNFULFILLED' END;
CREATE TABLE IF NOT EXISTS categories (
 id CHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, slug VARCHAR(140) NOT NULL UNIQUE,
 description TEXT NULL, image_url VARCHAR(1000) NULL, sort_order INT NOT NULL DEFAULT 0,
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS collections (
 id CHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, slug VARCHAR(140) NOT NULL UNIQUE,
 description TEXT NULL, image_url VARCHAR(1000) NULL, is_featured TINYINT(1) NOT NULL DEFAULT 0,
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS collection_products (
 collection_id CHAR(36) NOT NULL, product_id VARCHAR(80) NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 PRIMARY KEY(collection_id,product_id), FOREIGN KEY(collection_id) REFERENCES collections(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inventory_transactions (
 id CHAR(36) PRIMARY KEY, product_id VARCHAR(80) NOT NULL, actor_id CHAR(36) NULL,
 type ENUM('RECEIVED','REMOVED','ADJUSTMENT','ORDER_DEDUCTION','ORDER_RESTOCK','DAMAGED','EXPIRED') NOT NULL,
 previous_quantity INT NOT NULL, new_quantity INT NOT NULL, quantity_change INT NOT NULL,
 reason VARCHAR(255) NOT NULL, reference VARCHAR(120) NULL, notes TEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_inventory_product_date(product_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_events (
 id CHAR(36) PRIMARY KEY, order_id CHAR(36) NOT NULL, actor_id CHAR(36) NULL,
 event_type VARCHAR(60) NOT NULL, description VARCHAR(500) NOT NULL, metadata JSON NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE SET NULL, INDEX idx_order_events(order_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS refunds (
 id CHAR(36) PRIMARY KEY, order_id CHAR(36) NOT NULL, payment_id CHAR(36) NULL,
 provider_ref VARCHAR(190) NULL, amount_cents INT NOT NULL, currency VARCHAR(10) NOT NULL DEFAULT 'AUD',
 status ENUM('PENDING','SUCCEEDED','FAILED') NOT NULL DEFAULT 'PENDING', reason VARCHAR(500) NULL,
 created_by CHAR(36) NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(payment_id) REFERENCES payments(id) ON DELETE SET NULL,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS discounts (
 id CHAR(36) PRIMARY KEY, code VARCHAR(60) NOT NULL UNIQUE,
 type ENUM('PERCENT','FIXED','FREE_SHIPPING') NOT NULL, value INT NOT NULL DEFAULT 0,
 minimum_order_cents INT NOT NULL DEFAULT 0, usage_limit INT NULL, per_customer_limit INT NULL,
 starts_at DATETIME NULL, expires_at DATETIME NULL, is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS discount_uses (
 id CHAR(36) PRIMARY KEY, discount_id CHAR(36) NOT NULL, order_id CHAR(36) NOT NULL,
 user_id CHAR(36) NULL, discount_cents INT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_discount_order(order_id), FOREIGN KEY(discount_id) REFERENCES discounts(id),
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS product_reviews (
 id CHAR(36) PRIMARY KEY, product_id VARCHAR(80) NOT NULL, user_id CHAR(36) NULL,
 rating TINYINT NOT NULL, title VARCHAR(180) NULL, body TEXT NOT NULL,
 status ENUM('PENDING','APPROVED','REJECTED','HIDDEN') NOT NULL DEFAULT 'PENDING',
 moderated_by CHAR(36) NULL, moderated_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL,
 FOREIGN KEY(moderated_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
 id CHAR(36) PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
 status ENUM('SUBSCRIBED','UNSUBSCRIBED','PENDING') NOT NULL DEFAULT 'PENDING',
 consent_source VARCHAR(100) NULL, consent_at DATETIME NULL, unsubscribed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS customer_notes (
 id CHAR(36) PRIMARY KEY, customer_id CHAR(36) NOT NULL, actor_id CHAR(36) NULL,
 note TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS store_bundles (
 id CHAR(36) PRIMARY KEY, name VARCHAR(150) NOT NULL, slug VARCHAR(160) NOT NULL UNIQUE,
 description TEXT NULL, price_cents INT NOT NULL, is_active TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bundle_items (
 bundle_id CHAR(36) NOT NULL, product_id VARCHAR(80) NOT NULL, quantity INT NOT NULL,
 PRIMARY KEY(bundle_id,product_id), FOREIGN KEY(bundle_id) REFERENCES store_bundles(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS account_deletion_requests (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, reason VARCHAR(500) NULL,
 status ENUM('REQUESTED','PROCESSING','COMPLETED','DECLINED') NOT NULL DEFAULT 'REQUESTED',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
ALTER TABLE users ADD COLUMN email_verified_at DATETIME NULL;
CREATE TABLE IF NOT EXISTS email_verifications (
 id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at DATETIME NOT NULL, used_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_email_verification_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
